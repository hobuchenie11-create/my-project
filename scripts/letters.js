const fs = require("fs");
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, convertMillimetersToTwip,
} = require("docx");

const FONT = "Times New Roman";
const SIZE = 24;        // 12 pt (half-points)
const INDENT = { firstLine: convertMillimetersToTwip(12.5) };

const p = (text, opts = {}) =>
  new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    indent: opts.indent === false ? undefined : (opts.indent || INDENT),
    spacing: { after: opts.after === undefined ? 120 : opts.after, line: 276 },
    children: [new TextRun({ text, font: FONT, size: SIZE, bold: !!opts.bold,
                             italics: !!opts.italics })],
  });

const empty = () => p("", { after: 0, indent: false });

const header = (lines) =>
  lines.map((line) => p(line, { align: AlignmentType.RIGHT, indent: false, after: 0 }));

const doc = (children) =>
  new Document({
    styles: { default: { document: { run: { font: FONT, size: SIZE } } } },
    sections: [{
      properties: {
        page: {
          margin: {
            top: convertMillimetersToTwip(20),
            right: convertMillimetersToTwip(15),
            bottom: convertMillimetersToTwip(20),
            left: convertMillimetersToTwip(30),
          },
        },
      },
      children,
    }],
  });

