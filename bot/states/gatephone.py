"""Состояния заявки «Сменить номер на воротах».

Три вопроса по очереди: на кого оформлен номер, квартира, новый номер.
Одним сообщением житель пишет как придётся — «Иванова, 89…», без квартиры,
и председателю приходится переспрашивать.
"""
from aiogram.fsm.state import State, StatesGroup


class GatePhone(StatesGroup):
    name = State()        # ФИО владельца номера
    apartment = State()   # квартира
    phone = State()       # новый номер телефона
