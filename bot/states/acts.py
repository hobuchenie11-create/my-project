"""Состояния сценария «Передать акт поверки».

Квартира, какой прибор, сам документ — по одному вопросу за раз. Акт
житель присылает фотографией или файлом, бот его не читает: он передаёт
документ председателю и ведёт список квартир для письма ресурснику.
"""
from aiogram.fsm.state import State, StatesGroup


class MeterAct(StatesGroup):
    apartment = State()   # номер квартиры
    kind = State()        # какой прибор: ГВС, ХВС, электроэнергия
    document = State()    # фото или файл акта
