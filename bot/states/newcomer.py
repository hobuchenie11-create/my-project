"""Состояния сценария «Новый собственник».

Три вопроса из памятки, по одному за раз: квартира, ФИО с телефоном, номер
автомобиля. Разом список из нескольких пунктов люди выполняют наполовину —
отвечают на первое и забывают про телефон.

Копию выписки из ЕГРН бот не спрашивает: документ с персональными данными
житель отправляет председателю напрямую, а в переписке с ботом он только
лишний раз хранится.
"""
from aiogram.fsm.state import State, StatesGroup


class Newcomer(StatesGroup):
    apartment = State()   # какая квартира — житель ещё не в реестре
    contacts = State()    # ФИО и телефон для ворот
    car = State()         # номер авто или «нет»
