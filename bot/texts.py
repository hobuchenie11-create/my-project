def _days_word(count: int) -> str:
    if count % 10 == 1 and count % 100 != 11:
        return f"{count} день"
    if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        return f"{count} дня"
    return f"{count} дней"


def collection_reminder_text(today: date | None = None) -> str:
    """Короткое напоминание в чат дома: до какого числа передать показания.

    Дата считается от текущего месяца, поэтому текст не устаревает — одну и ту
    же кнопку можно нажимать каждый месяц.
    """
    today = today or date.today()
    last_day = config.readings_day_end
    deadline = f"{last_day} {MONTHS_GENITIVE[today.month - 1]}"

    left = last_day - today.day
    if left > 0:
        urgency = f"Остаётся {_days_word(left)}."
    elif left == 0:
        urgency = "<b>Сегодня последний день.</b>"
    else:
        urgency = ("Срок сбора завершён — показания ещё примут, но учтут "
                   "в следующем расчётном периоде.")

    return (
        "🔔 <b>Показания счётчиков — напоминание</b>\n\n"
        "С августа показания в нашем доме принимает и обрабатывает "
        "автоматическая система <b>«Домовед»</b>: итоговый реестр с "
        "показаниями формируется теперь в автоматическом режиме.\n\n"
        f"🗓 Просьба передать показания <b>до {deadline}</b> включительно. "
        f"{urgency}\n\n"
        "<b>Как передать — любым способом:</b>\n"
        "• сообщением прямо в этот чат по шаблону;\n"
        "• в самом боте кнопкой «🏠 Передать показания».\n\n"
        "<b>Шаблон для 1-2 комн. квартир:</b>\n"
        f"<code>{TEMPLATE_SMALL}</code>\n\n"
        "<b>Шаблон для 3-х комн. квартир:</b>\n"
        f"<code>{TEMPLATE_LARGE}</code>\n\n"
        "❗ Номер квартиры — <b>в первой строке</b>.\n"
        "✅ Подтверждение о приёме приходит лично в бот. Если его не получаете "
        "— откройте Домоведа и нажмите <b>Старт</b>.\n\n"
        "Своевременно переданные показания — это ответственность каждого "
        "жителя, что позволяет минимизировать расход по ОДН. Благодарю всех "
        "за понимание и участие в процессе сбора показаний по нашему дому. 🙏"
    )


