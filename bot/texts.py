"""Тексты для жителей (памятка/приветствие/уведомления)."""
from bot.config import config


def late_submission_text() -> str:
    """Сообщение жителю, передавшему показания после срока сбора."""
    return (
        "⏰ <b>Показания приняты, но переданы после срока сбора.</b>\n\n"
        f"Сбор показаний проходит с {config.readings_day_start} по "
        f"{config.readings_day_end} число, ведомость передаётся "
        f"{config.statement_day} числа. Ваши показания будут учтены "
        "<b>в следующем расчётном периоде</b>.\n\n"
        "💡 Чтобы показания попали в текущий расчёт, их также можно передать:\n"
        "• при оплате квитанции;\n"
        "• через личный кабинет на сайте ресурсоснабжающей организации.\n\n"
        f"В следующем месяце передайте, пожалуйста, показания с "
        f"{config.readings_day_start} по {config.readings_day_end} число. Спасибо!"
    )


